const NAMESPACE_FLAGS: u64 = (libc::CLONE_NEWNS
    | libc::CLONE_NEWUTS
    | libc::CLONE_NEWIPC
    | libc::CLONE_NEWUSER
    | libc::CLONE_NEWPID
    | libc::CLONE_NEWNET
    | libc::CLONE_NEWCGROUP) as u64;

pub fn load() -> Result<(), String> {
    let fail = |e: libseccomp::error::SeccompError| format!("seccomp: {e}");
    let mut filter = ScmpFilterContext::new_filter(ScmpAction::Errno(libc::EPERM)).map_err(fail)?;
    for name in ALLOWED {
        if let Ok(syscall) = ScmpSyscall::from_name(name) {
            // Some names exist in libseccomp's tables but not on this architecture.
            let _ = filter.add_rule(ScmpAction::Allow, syscall);
        }
    }
    // Threads and processes, but no new namespaces from inside.
    let clone = ScmpSyscall::from_name("clone").map_err(fail)?;
    let no_namespaces = ScmpArgCompare::new(0, ScmpCompareOp::MaskedEqual(NAMESPACE_FLAGS), 0);
    filter
        .add_rule_conditional(ScmpAction::Allow, clone, &[no_namespaces])
        .map_err(fail)?;
    // clone3 passes its flags in memory, where seccomp can't look. Saying it doesn't exist
    // makes the C library fall back to clone, as under Docker.
    if let Ok(clone3) = ScmpSyscall::from_name("clone3") {
        filter
            .add_rule(ScmpAction::Errno(libc::ENOSYS), clone3)
            .map_err(fail)?;
    }
    filter.load().map_err(fail)
}
