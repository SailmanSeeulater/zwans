def git_repo(root: Path, branch: str = "feature") -> None:
    env = {
        **os.environ,
        "GIT_AUTHOR_NAME": "t",
        "GIT_AUTHOR_EMAIL": "t@example.com",
        "GIT_COMMITTER_NAME": "t",
        "GIT_COMMITTER_EMAIL": "t@example.com",
    }
    subprocess.run(["git", "init", "-q", "-b", branch], cwd=root, check=True, env=env)
    (root / "a.txt").write_text("a\n")
    subprocess.run(["git", "add", "a.txt"], cwd=root, check=True, env=env)
    subprocess.run(["git", "commit", "-q", "-m", "first"], cwd=root, check=True, env=env)


def calls(data: Path) -> list[list[str]]:
    return [json.loads(line) for line in (data / "calls.log").read_text().splitlines()]


def runs_list(*runs: tuple[int, str, str | None, str]) -> str:
    return json.dumps(
        [
            {
                "databaseId": run_id,
                "status": status,
                "conclusion": conclusion,
                "workflowName": workflow,
                "displayTitle": f"Commit {run_id}",
                "headSha": f"{run_id:07d}abcdef",
                "event": "push",
                "createdAt": "2026-11-24T11:41:01Z",
                "url": f"https://github.com/o/r/actions/runs/{run_id}",
            }
            for run_id, status, conclusion, workflow in runs
        ]
    )


