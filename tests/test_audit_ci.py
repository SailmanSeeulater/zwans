def test_ci_explains_the_latest_failed_run_on_the_current_branch(
    tmp_path: Path, ctx: ToolContext, fake_gh: Path
) -> None:
    git_repo(tmp_path)
    (fake_gh / "list.json").write_text(
        runs_list(
            (300, "in_progress", None, "CI"),
            (200, "completed", "failure", "CI"),
            (100, "completed", "success", "CI"),
        )
    )
    (fake_gh / "view.json").write_text(
        view(
            [
                job("lint", "success", [(1, "Set up job", "success")], 1),
                job(
                    "check (ubuntu-latest)",
                    "failure",
                    [
                        (1, "Set up job", "success"),
                        (10, "Run mypy", "failure"),
                        (11, "Run pytest", "skipped"),
                    ],
                    2,
                ),
                job("check (windows-latest)", "cancelled", [], 3),
            ]
        )
    )
    (fake_gh / "log.txt").write_text(log_lines("check (ubuntu-latest)", "Run mypy", MYPY_LOG))

    output = run(CITool(), CIInput(), ctx).content
    assert output.splitlines()[:3] == [
        'Run 200: CI "Add the thing": failure',
        "Commit abcdef1 on feature, push  https://github.com/o/r/actions/runs/200",
        'The latest run, CI "Commit 300" (0000300), is still in_progress.',
    ]
    assert "Failed jobs: 1 of 3.\nCancelled: check (windows-latest)." in output
    assert (
        'Job "check (ubuntu-latest)": failure\n  Failed step 10: "Run mypy"\n  Log (all 4 lines):'
        in output
    )
    assert (
        '    src/app.py:210: error: Cannot find implementation or library stub for module named "playwright"  [import-not-found]'
        in output
    )
    assert "    error: Process completed with exit code 1." in output
    for noise in ("2026-11-24T", "\x1b[", "shell: /usr/bin/bash", "pythonLocation", "##[", "﻿"):
        assert noise not in output
    assert calls(fake_gh)[0][:4] == ["run", "list", "--branch", "feature"]
    assert ["run", "view", "200", "--log-failed"] in calls(fake_gh)


