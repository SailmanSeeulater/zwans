class FakeOSV:
    def __init__(self) -> None:
        self.batches: list[int] = []
        self.fetched: list[str] = []

    def __call__(self, request: httpx.Request) -> httpx.Response:
        assert request.url.host == "api.osv.dev"
        if request.method == "POST" and request.url.path == "/v1/querybatch":
            queries = json.loads(request.content)["queries"]
            self.batches.append(len(queries))
            results = []
            for query in queries:
                key = (query["package"]["ecosystem"], query["package"]["name"], query["version"])
                ids = VULNERABLE.get(key, [])
                results.append(
                    {"vulns": [{"id": i, "modified": "2024-01-01T00:00:00Z"} for i in ids]}
                    if ids
                    else {}
                )
            return httpx.Response(200, json={"results": results})
        if request.method == "GET" and request.url.path.startswith("/v1/vulns/"):
            vuln_id = request.url.path.rsplit("/", 1)[1]
            self.fetched.append(vuln_id)
            if vuln_id in DETAILS:
                return httpx.Response(200, json=DETAILS[vuln_id])
            return httpx.Response(404, json={"message": "Bug not found."})
        return httpx.Response(400)


