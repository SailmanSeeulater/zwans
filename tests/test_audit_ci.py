def test_ci_takes_a_job_url_and_a_job_filter(
    tmp_path: Path, ctx: ToolContext, fake_gh: Path
) -> None:
    (fake_gh / "view.json").write_text(
        view(
            [
                job("check (ubuntu-latest)", "failure", [(10, "Run mypy", "failure")], 11),
                job("check (windows-latest)", "failure", [(10, "Run mypy", "failure")], 12),
            ]
        )
    )
    (fake_gh / "log.txt").write_text(
        log_lines("check (ubuntu-latest)", "Run mypy", ["ubuntu broke"])
        + log_lines("check (windows-latest)", "Run mypy", ["windows broke"])
    )
    url = "https://github.com/other/repo/actions/runs/200/job/12"
    output = run(CITool(), CIInput(run=url), ctx).content
    assert "windows broke" in output and "ubuntu broke" not in output
    assert calls(fake_gh)[0] == [
        "run",
        "view",
        "200",
        "--repo",
        "other/repo",
        "--json",
        "jobs,conclusion,status,url,workflowName,displayTitle,headSha,headBranch,event",
    ]

    output = run(CITool(), CIInput(run="200", job="UBUNTU"), ctx).content
    assert "ubuntu broke" in output and "windows broke" not in output
    with pytest.raises(
        ToolError,
        match=r"No failed job's name contains 'mac'. Failed jobs: check \(ubuntu-latest\), check \(windows-latest\).",
    ):
        run(CITool(), CIInput(run="200", job="mac"), ctx)
    with pytest.raises(ToolError, match="run should be a run id"):
        run(CITool(), CIInput(run="yesterday's"), ctx)


