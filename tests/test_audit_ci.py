def test_ci_errors_are_clear(
    tmp_path: Path, ctx: ToolContext, fake_gh: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    with pytest.raises(ToolError, match="isn't a git repository"):
        run(CITool(), CIInput(), ctx)

    git_repo(tmp_path)
    (fake_gh / "fail.txt").write_text(
        "To get started with GitHub CLI, please run:  gh auth login\n"
    )
    with pytest.raises(
        ToolError,
        match="gh isn't logged in to GitHub: To get started with GitHub CLI, please run:  gh auth login",
    ):
        run(CITool(), CIInput(), ctx)

    (fake_gh / "fail.txt").write_text(
        "none of the git remotes configured for this repository point to a known GitHub host\n"
    )
    with pytest.raises(ToolError, match="has no GitHub remote: none of the git remotes"):
        run(CITool(), CIInput(), ctx)

    empty = tmp_path.parent / f"{tmp_path.name}-nothing"
    empty.mkdir()
    monkeypatch.setenv("PATH", str(empty))
    assert available() is False
    with pytest.raises(ToolError, match=r"The GitHub CLI \(gh\) isn't installed"):
        run(CITool(), CIInput(run="1"), ctx)


