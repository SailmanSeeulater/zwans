@pytest.mark.skipif(shutil.which("rg") is None, reason="needs ripgrep")
def test_audit_finds_the_lockfiles_in_a_folder_and_lists_the_vulnerable_packages(
    tmp_path: Path, ctx: ToolContext
) -> None:
    write_fixtures(tmp_path)
    osv = FakeOSV()
    output = run(AuditTool(transport=httpx.MockTransport(osv)), AuditInput(), ctx).content

    head, _, rest = output.partition("\n\n")
    assert head.splitlines()[0].startswith("Checked ")
    for path in (
        "uv.lock",
        "requirements.txt",
        "web/package-lock.json",
        "web/yarn.lock",
        "web/pnpm-lock.yaml",
        "svc/go.sum",
    ):
        assert f"  {path} " in head
    assert "node_modules" not in head
    assert "(2 unpinned lines skipped)" in head
    assert len(osv.batches) == 1  # every lockfile's packages in one request

    # Most severe first: lodash (HIGH 7.2), then jinja2 (5.4), then x/text (no severity)
    assert (
        rest.index("lodash 4.17.20 (npm, web/package-lock.json, web/pnpm-lock.yaml, web/yarn.lock)")
        < rest.index("jinja2 3.1.2 (PyPI, uv.lock)")
        < rest.index("golang.org/x/text v0.3.0 (Go, svc/go.sum)")
    )
    assert "3 vulnerable packages (3 advisories)" in rest
    assert (
        "GHSA-35jh-r3h4-6jhm / CVE-2021-23337  HIGH 7.2: Command Injection in lodash (fixed in 4.17.21)"
        in rest
    )
    # The GHSA and PYSEC copies of one vulnerability are listed once, with the GHSA's severity
    assert (
        "GHSA-h75v-3vvj-5mfj / CVE-2024-34064  MODERATE 5.4: Jinja vulnerable to HTML attribute injection (fixed in 3.1.4)"
        in rest
    )
    jinja = rest.split("jinja2 3.1.2", 1)[1].split("\n\n")[0]
    assert jinja.count("\n  - ") == 1 and "PYSEC" not in jinja
    assert "GO-2020-0015 / CVE-2020-14040 / GHSA-5rcv-m4m3-hfh7: Infinite loop" in rest
    assert "(fixed in 0.3.3)" in rest
    assert osv.fetched[0].startswith("GHSA-")


